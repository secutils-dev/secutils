// Table column layout in rendered HTML. This module turns the `su-table` comment of a table into
// a `<colgroup>`. The live preview, the review "before" popover, and the export render share it,
// so a table has the same proportions in each. Source parsing and edits live in `table.ts`.
// The comment is document content: widths pass `metadataWidths` before they reach a style.
import { metadataWidths } from './table.ts';

/**
 * Converts a raw HTML token that is exactly a `su-table` comment with valid widths into an inert
 * carrier element. Returns null for any other token, and the caller then sanitizes that token.
 *
 * Only validated numeric layout crosses the raw-HTML sanitizer. This carrier is
 * generated by the renderer; raw HTML cannot supply its data attribute.
 */
export function tableMetadataHtml(text: string): string | null {
    const match = text.match(/^\s*<!--\s*su-table\s+([^\r\n]*?)\s*-->\s*$/);
    if (!match) return null;
    try {
        const value = JSON.parse(match[1]),
            widths = metadataWidths(match[1], value?.cols?.length ?? 0);
        return widths ? `<span data-su-table-layout="${widths.join(',')}" hidden></span>` : null;
    } catch {
        return null;
    }
}

/**
 * Sets the column widths of a table as percentages in a generated `<colgroup>`, and replaces the
 * previous generated one. `null` removes it and returns the table to automatic layout.
 *
 * @param widths Column shares that sum to 1, one for each column.
 */
export function setTableWidths(table: HTMLTableElement, widths: number[] | null) {
    table.querySelector(':scope > colgroup[data-su-table]')?.remove();
    table.classList.toggle('su-sized-table', !!widths);
    if (!widths) return;
    const group = document.createElement('colgroup');
    group.dataset.suTable = '';
    for (const width of widths) {
        const col = document.createElement('col');
        col.style.width = `${width * 100}%`;
        group.append(col);
    }
    table.prepend(group);
}

/**
 * Applies each layout marker under `root` to the table that directly follows it, and removes the
 * marker where the output must not keep it.
 * Read layout from adjacent inert Markdown comments, in both fresh previews and export rendering.
 *
 * Widths apply only when their count equals the cell count of the first table row. A marker
 * without a table after it has no effect, and its carrier element leaves the DOM.
 *
 * @param forExport Remove the marker of each table. In the live preview (`false`), a marker in
 *   its own source block gives its `data-start` to the table block and leaves the DOM. The table
 *   block then covers the comment and the table, like `TableModel.start`.
 */
export function applyTableLayouts(root: HTMLElement, forExport: boolean) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_COMMENT);
    const markers: { node: Comment | HTMLElement; metadata: string }[] = [];
    while (walker.nextNode()) {
        const node = walker.currentNode as Comment,
            match = node.data.match(/^\s*su-table\s+([^\r\n]*?)\s*$/);
        if (match) markers.push({ node, metadata: match[1] });
    }
    for (const node of root.querySelectorAll<HTMLElement>('[data-su-table-layout]'))
        markers.push({
            node,
            metadata: JSON.stringify({ v: 1, cols: node.getAttribute('data-su-table-layout')!.split(',').map(Number) }),
        });
    for (const { node, metadata } of markers) {
        // The source-mapped preview wraps a marker in a block of its own.
        const parent = node.parentElement;
        const block =
            parent?.matches('.su-block') &&
            [...parent.childNodes].every(
                (n) =>
                    n === node ||
                    n.nodeType === Node.COMMENT_NODE ||
                    (n.nodeType === Node.TEXT_NODE && !n.textContent?.trim()),
            )
                ? parent
                : null;
        let next: ChildNode | null = (block ?? node).nextSibling;
        while (next?.nodeType === Node.TEXT_NODE && !next.textContent?.trim()) next = next.nextSibling;
        const element = next instanceof HTMLElement ? next : null;
        const table =
            element instanceof HTMLTableElement
                ? element
                : element?.matches('.su-block') && element.firstElementChild instanceof HTMLTableElement
                  ? element.firstElementChild
                  : null;
        if (!table) {
            if (node instanceof HTMLElement) node.remove();
            continue;
        }
        const widths = metadataWidths(metadata, table.rows[0]?.cells.length ?? 0);
        setTableWidths(table, widths);
        if (block && !forExport && element) {
            element.dataset.start = block.dataset.start;
            block.remove();
        } else if (forExport || node instanceof HTMLElement) node.remove();
    }
}
